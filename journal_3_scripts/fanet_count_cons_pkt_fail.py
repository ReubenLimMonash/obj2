def process_run_waypoint_time_window(run_number, scenario_path, dl_delay_threshold, ul_delay_threshold, max_time, n_secs):
    '''
    Searches for occurence of time windows (length n_sec) in which no packets are received for each link.
    NOTE: Provide file_path such that the files for a particular run number can be identified using glob.glob(file_path.format(run_number))
    '''
    file_path = os.path.join(scenario_path, "Run-{}_*.csv")
    run_files = glob.glob(file_path.format(run_number)) # Get list of csv files belonging to this scenario

    rx_df_list = compile_rx_data(run_files)
    switch_time_df = pd.read_csv(os.path.join(scenario_path, "Run-{}_Switch_Time.csv".format(run_number)))
    
    # uavs_rx_df = pd.concat(rx_df_list[1:len(rx_df_list)], ignore_index=True) # Includes GW Rx DF and all UAVs Rx DFs

    # Find presence of n consecutive packet loss in GCS Rx
    gcs_cons_fail = 0 # 0 indicates no n consecutive packet failure, 1 means yes
    gcs_rx_df = rx_df_list[0]
    gcs_rx_df["Delay"] = gcs_rx_df['RxTime']-gcs_rx_df['TxTime'] # Calc delay of packets received
    gcs_reliable_rx_df = gcs_rx_df.loc[['Waypoint' in name for name in gcs_rx_df.Packet_Name] & (gcs_rx_df["Delay"]<=ul_delay_threshold)]
    try:
        switch_time = switch_time_df.loc[[True if "GCS" in x else False for x in switch_time_df["Module"]]]["Switch_Time"].values[0]
        if (max_time - switch_time) >= n_secs: # If at least n_secs elapsed after switch time
            # Use time window of size n_secs and stride of 1 sec
            for i in range(math.floor((max_time - switch_time - n_secs) + 1)):
                # Check for any reliably received waypoint packets within the time window spanning (i) to (i+n_secs)
                rx_df_in_range = gcs_reliable_rx_df.loc[(gcs_reliable_rx_df["RxTime"] >= (switch_time+i)) & (gcs_reliable_rx_df["RxTime"] < (switch_time+i+n_secs))] # Get reliable rcvd packets within time window
                if rx_df_in_range.empty:
                    gcs_cons_fail = 1
                    break
        else: # In this case, set to nan
            gcs_cons_fail = np.nan
    except Exception as e:
        # print(run_number)
        # print(e)
        gcs_cons_fail = np.nan

    # Find presence of n consecutive packet loss in UAVs' Rx DFs     
    uavs_cons_fail = np.zeros(len(rx_df_list)-1)
    for i in range(1,len(rx_df_list)):
        uav_rx_df = rx_df_list[i]
        uav_rx_df["Delay"] = uav_rx_df['RxTime']-uav_rx_df['TxTime']
        uav_reliable_rx_df = uav_rx_df.loc[['Waypoint' in name for name in uav_rx_df.Packet_Name] & (uav_rx_df["Delay"]<=dl_delay_threshold)]
        try:
            if i == 1: # This is the gateway
                switch_time = switch_time_df.loc[[True if "gatewayNode" in x else False for x in switch_time_df["Module"]]]["Switch_Time"].values[0]
            else:
                switch_time = switch_time_df.loc[[True if "adhocNode[{}]".format(i-2) in x else False for x in switch_time_df["Module"]]]["Switch_Time"].values[0]
            if (max_time - switch_time) >= n_secs: # If at least n_secs elapsed after switch time
                # Use time window of size n_secs and stride of 1 sec
                for j in range(math.floor((max_time - switch_time - n_secs) + 1)):
                    # Check for any reliably received waypoint packets within the time window spanning (j) to (j+n_secs)
                    rx_df_in_range = uav_reliable_rx_df.loc[(uav_reliable_rx_df["RxTime"] >= (switch_time + j)) & (uav_reliable_rx_df["RxTime"] < (switch_time + j + n_secs))] # Get reliable rcvd packets within time window
                    if rx_df_in_range.empty:
                        uavs_cons_fail[i-1] = 1
                        break
            else: # In this case, set to nan
                uavs_cons_fail[i-1] = np.nan
        except Exception as e:
            # print(run_number)
            # print(e)
            uavs_cons_fail[i-1] = np.nan
        
    return (run_number, gcs_cons_fail, *uavs_cons_fail)

