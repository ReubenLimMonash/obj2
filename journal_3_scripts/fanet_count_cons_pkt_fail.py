def process_run_manual(run_number, scenario_path, dl_delay_threshold, ul_delay_threshold, switch_time, max_time, n_period, usi):
    '''
    For manual mode (switch time must be provided, assumes all link switch same time)
    Searches for gaps of length n_secs between packet receptions for each link.
    If such gaps are identified, it will return 1 for the link.
    NOTE: Provide file_path such that the files for a particular run number can be identified using glob.glob(file_path.format(run_number))
          Max time should be the time the Tx app stops
          usi must be given in ms
    '''
    file_path = os.path.join(scenario_path, "Run-{}_*.csv")
    run_files = glob.glob(file_path.format(run_number)) # Get list of csv files belonging to this scenario

    rx_df_list = compile_rx_data(run_files)

    # Find presence of n consecutive packet loss in GCS Rx
    gcs_cons_fail = 0 # 0 indicates no n consecutive packet failure, 1 means yes
    gcs_rx_df = rx_df_list[0]
    gcs_rx_df["Delay"] = gcs_rx_df['RxTime']-gcs_rx_df['TxTime'] # Calc delay of packets received
    gcs_reliable_rx_df = gcs_rx_df.loc[['Waypoint' in name for name in gcs_rx_df.Packet_Name] & (gcs_rx_df["Delay"]<=ul_delay_threshold)]
    n_secs = n_period * 20 / 1000 # GCS sending interval is 20 ms for DJI Spark
    if (max_time - switch_time) >= n_secs: # If at least n_secs elapsed after switch time
        gcs_reliable_rx_df = gcs_reliable_rx_df.loc[gcs_reliable_rx_df["TxTime"]>=switch_time]
        # Append switch time and front and max time at back, so that can check if there is a gap >= n_sec between first packet after switch with swicth time, and between last packet and max time
        rx_time_series = pd.concat([pd.Series([switch_time]), gcs_reliable_rx_df["RxTime"], pd.Series([max_time])])
        rx_time_diff = rx_time_series.diff().dropna()
        if not rx_time_diff.empty:
            if rx_time_diff.gt(n_secs + ul_delay_threshold).any():
                gcs_cons_fail = 1
    else: # In this case, set to nan
        gcs_cons_fail = np.nan

    # Find presence of n consecutive packet loss in UAVs' Rx DFs     
    uavs_cons_fail = np.zeros(len(rx_df_list)-1)
    n_secs = n_period * usi / 1000 # GCS sending interval is 20 ms for DJI Spark
    for i in range(1,len(rx_df_list)):
        uav_rx_df = rx_df_list[i]
        uav_rx_df["Delay"] = uav_rx_df['RxTime']-uav_rx_df['TxTime']
        uav_reliable_rx_df = uav_rx_df.loc[['Waypoint' in name for name in uav_rx_df.Packet_Name] & (uav_rx_df["Delay"]<=dl_delay_threshold)]  
        if (max_time - switch_time) >= n_secs: # If at least n_secs elapsed after switch time
            uav_reliable_rx_df = uav_reliable_rx_df.loc[uav_reliable_rx_df["TxTime"]>=switch_time]
            # Append switch time and front and max time at back, so that can check if there is a gap >= n_sec between first packet after switch with swicth time, and between last packet and max time
            rx_time_series = pd.concat([pd.Series([switch_time]), uav_reliable_rx_df["RxTime"], pd.Series([max_time])])
            rx_time_diff = rx_time_series.diff().dropna()
            if not rx_time_diff.empty:
                # if rx_time_diff.gt(n_secs + dl_delay_threshold).any():
                if rx_time_diff.gt(n_secs).any():
                    uavs_cons_fail[i-1] = 1
        else: # In this case, set to nan
            uavs_cons_fail[i-1] = np.nan
        
    return (run_number, gcs_cons_fail, *uavs_cons_fail)

